CREATE DATABASE LIBRARY_MANAGEMENT_SYSTEM;
USE LIBRARY_MANAGEMENT_SYSTEM;

CREATE TABLE AUTHORS (
    AUTHOR_ID INT PRIMARY KEY,
    AUTHOR_NAME VARCHAR(100) NOT NULL,
    COUNTRY VARCHAR(50)
);

CREATE TABLE CATEGORIES (
    CATEGORY_ID INT PRIMARY KEY,
    CATEGORY_NAME VARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE BOOKS (
    BOOK_ID INT PRIMARY KEY,
    TITLE VARCHAR(255) NOT NULL,
    ISBN VARCHAR(20) UNIQUE NOT NULL,
    PUBLISHED_YEAR DATE,
    TOTAL_COPIES INT CHECK (TOTAL_COPIES >= 0),
    AVAILABLE_COPIES INT CHECK (AVAILABLE_COPIES >= 0),

    AUTHOR_ID INT,
    CATEGORY_ID INT,

    CONSTRAINT FK_BOOK_AUTHOR
        FOREIGN KEY (AUTHOR_ID)
        REFERENCES AUTHORS(AUTHOR_ID),

    CONSTRAINT FK_BOOK_CATEGORY
        FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORIES(CATEGORY_ID)
);

CREATE TABLE STUDENTS (
    STUDENT_ID INT PRIMARY KEY,
    STUDENT_NAME VARCHAR(100) NOT NULL,
    DEPARTMENT VARCHAR(100),
    EMAIL VARCHAR(100) UNIQUE,
    PHONE_NO VARCHAR(15),
    JOIN_DATE DATE DEFAULT (CURRENT_DATE)
);

CREATE TABLE BOOK_ISSUES (
    ISSUE_ID INT PRIMARY KEY,

    STUDENT_ID INT,
    BOOK_ID INT,

    ISSUE_DATE DATE NOT NULL,
    DUE_DATE DATE NOT NULL,
    RETURN_DATE DATE,

    CONSTRAINT FK_ISSUE_STUDENT
        FOREIGN KEY (STUDENT_ID)
        REFERENCES STUDENTS(STUDENT_ID),

    CONSTRAINT FK_ISSUE_BOOK
        FOREIGN KEY (BOOK_ID)
        REFERENCES BOOKS(BOOK_ID)
);

CREATE TABLE FINES (
    FINE_ID INT PRIMARY KEY,

    ISSUE_ID INT UNIQUE,

    FINE_AMOUNT DECIMAL(10,2) CHECK (FINE_AMOUNT >= 0),

    PAID_STATUS VARCHAR(20)
        CHECK (PAID_STATUS IN ('Paid', 'Unpaid')),

    CONSTRAINT FK_FINE_ISSUE
        FOREIGN KEY (ISSUE_ID)
        REFERENCES BOOK_ISSUES(ISSUE_ID)
);


